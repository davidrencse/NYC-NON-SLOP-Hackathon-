import assert from 'node:assert/strict';
import { actorAt, hitActor, boost } from '../forge_research/web/diorama/whip-state.mjs';
const crew = [{}, {}];
const mesh = index => ({ userData: { crew: index } });
assert.equal(actorAt([{ object: { parent: mesh(1) } }, { object: mesh(0) }], crew), crew[1]);
assert.equal(actorAt([], crew), null);
hitActor(null, 0);
hitActor(crew[0], 100);
assert.equal(boost(crew[0], 101), 2);
assert.equal(boost(crew[1], 101), 1);
for (let i = 0; i < 1000; i++) hitActor(crew[0], i);
assert.equal(crew[0].whip.until, 999 + 2400);
assert.equal(boost(crew[0], 3400), 1);
assert.equal(crew[0].whip, null);
const { ropeAt, stepRope, crackReady, sweepPoints } = await import('../forge_research/web/diorama/whip-physics.mjs');
const a = ropeAt(0, 0), b = ropeAt(0, 0);
stepRope(a, { x: 80, y: 10 }, 100);
stepRope(b, { x: 80, y: 10 }, 1 / 30);
assert.deepEqual(a, b, 'long frame is clamped');
assert.equal(a[0].x, 80);
assert.ok(a.every(p => Number.isFinite(p.x) && Number.isFinite(p.y)));
assert.ok(a.at(-1).x !== a[0].x, 'tip lags handle');
assert.equal(crackReady(900, 1000, 500), false);
assert.equal(crackReady(900, 1200, 500), true);
assert.equal(crackReady(100, 2000, 0), false);
const sweep = sweepPoints({ x: 0, y: 0 }, { x: 15, y: 0 });
assert.deepEqual(sweep.at(-1), { x: 15, y: 0 });
assert.ok(sweep.some(p => p.x === 9), 'sweep covers between frames');
assert.ok(sweepPoints({ x: 0, y: 0 }, { x: 100000, y: 0 }).length <= 80);
assert.deepEqual(ropeAt(0, 0), ropeAt(0, 0), 'reset has no retained momentum');
console.log('voxel whip: selection, bounded boost, reset, dt clamp, lag, cooldown, swept tip passed');
